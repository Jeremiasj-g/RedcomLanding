create table if not exists public.category_scale_settings (
  id smallint primary key default 1 check (id = 1),
  title text not null default 'Escalas categorización preventa',
  valid_year integer not null default 2026,
  updated_at timestamptz not null default now(),
  updated_by uuid null references auth.users(id) on delete set null
);

insert into public.category_scale_settings(id, title, valid_year)
values (1, 'Escalas categorización preventa', 2026)
on conflict (id) do nothing;

create table if not exists public.category_scale_metrics (
  id bigint generated by default as identity primary key,
  section_name text not null,
  metric_name text not null,
  senior_requirement text not null,
  semi_senior_requirement text not null,
  junior_requirement text not null,
  improvement_requirement text not null,
  weight_percent numeric(6,2) not null default 0,
  sort_order integer not null default 100,
  is_active boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid null references auth.users(id) on delete set null
);

create table if not exists public.category_scale_gates (
  id bigint generated by default as identity primary key,
  label text not null,
  value_text text not null,
  sort_order integer not null default 100,
  is_active boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid null references auth.users(id) on delete set null
);

alter table public.category_scale_settings enable row level security;
alter table public.category_scale_metrics enable row level security;
alter table public.category_scale_gates enable row level security;

drop policy if exists category_scale_settings_admin_all on public.category_scale_settings;
create policy category_scale_settings_admin_all
on public.category_scale_settings
for all to authenticated
using (public.my_role() = 'admin')
with check (public.my_role() = 'admin');

drop policy if exists category_scale_metrics_admin_all on public.category_scale_metrics;
create policy category_scale_metrics_admin_all
on public.category_scale_metrics
for all to authenticated
using (public.my_role() = 'admin')
with check (public.my_role() = 'admin');

drop policy if exists category_scale_gates_admin_all on public.category_scale_gates;
create policy category_scale_gates_admin_all
on public.category_scale_gates
for all to authenticated
using (public.my_role() = 'admin')
with check (public.my_role() = 'admin');

